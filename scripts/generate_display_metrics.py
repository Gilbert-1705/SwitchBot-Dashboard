"""Generates the character width table of the display simulator.

The Weather Station renders the custom page with a Noto Sans CJK like
font. Character advances are taken from Noto Sans CJK Regular at the
size calibrated against photos of the real device (see
custom_components/switchbot_dashboard/simulator.py) and written to
simulator_metrics.py, so the simulator needs no font at runtime.

Run (needs Pillow and the Noto Sans CJK font):

    python3 scripts/generate_display_metrics.py [path/to/NotoSansCJK-Regular.ttc]
"""

import sys
from pathlib import Path

from PIL import ImageFont

FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"
# calibrated on photos IMG_3486/3488/3489 (2026-11-21): glyph size in
# device pixels of the 800x480 panel
FONT_SIZE = 54.6

# printable ASCII, Latin-1 and the symbols the widgets use
CHARS = (
    [chr(c) for c in range(0x20, 0x7F)]
    + [chr(c) for c in range(0xA0, 0x100)]
    + list("€–—…·•‹›„“”‘’₂³²↑↓←→○●⌂★☆✓✗♪")
)

TARGET = (
    Path(__file__).resolve().parent.parent
    / "custom_components" / "switchbot_dashboard" / "simulator_metrics.py"
)


def main(font_path: str = FONT) -> None:
    # large size for precision, scaled down afterwards
    font = ImageFont.truetype(font_path, 1000, index=0)

    widths = {}
    for char in CHARS:
        width = font.getlength(char) / 1000 * FONT_SIZE
        if width > 0:
            widths[char] = round(width, 1)

    lines = [
        '"""Character advances of the display font in device pixels.',
        "",
        "Generated by scripts/generate_display_metrics.py - do not edit.",
        '"""',
        "",
        f"FONT_SIZE = {FONT_SIZE}",
        "",
        "ADVANCES = {",
    ]
    for char, width in widths.items():
        lines.append(f"    {char!r}: {width},")
    lines.append("}")

    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(widths)} characters -> {TARGET}")


if __name__ == "__main__":
    main(*sys.argv[1:])
